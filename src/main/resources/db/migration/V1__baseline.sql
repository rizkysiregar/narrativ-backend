-- Baseline of the schema as mapped by the JPA entities.
-- Existing databases are baselined at version 1 (spring.flyway.baseline-on-migrate), so this
-- script only ever runs on an empty database. IF NOT EXISTS keeps it safe if it is replayed.

CREATE TABLE IF NOT EXISTS users (
    id            UUID         PRIMARY KEY,
    username      VARCHAR(16)  NOT NULL UNIQUE,
    password      VARCHAR(255) NOT NULL,
    email         VARCHAR(255) NOT NULL UNIQUE,
    first_name    VARCHAR(50),
    last_name     VARCHAR(50),
    phone_number  VARCHAR(13),
    created_at    TIMESTAMP(6) NOT NULL,
    profile_image VARCHAR(255),
    google_id     VARCHAR(255) UNIQUE,
    role          VARCHAR(20)  NOT NULL,
    is_deleted    BOOLEAN      NOT NULL
);

CREATE TABLE IF NOT EXISTS posts (
    id            UUID         PRIMARY KEY,
    user_id       UUID         NOT NULL REFERENCES users (id),
    caption       TEXT,
    media_url     VARCHAR(255) NOT NULL,
    media_type    VARCHAR(255) NOT NULL,
    thumbnail_url VARCHAR(255),
    created_at    TIMESTAMP(6) NOT NULL,
    is_deleted    BOOLEAN      NOT NULL
);

CREATE TABLE IF NOT EXISTS comments (
    id         UUID         PRIMARY KEY,
    post_id    UUID         NOT NULL REFERENCES posts (id),
    user_id    UUID         NOT NULL REFERENCES users (id),
    parent_id  UUID         REFERENCES comments (id),
    content    VARCHAR(255) NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS likes (
    id         UUID         PRIMARY KEY,
    user_id    UUID         NOT NULL REFERENCES users (id),
    post_id    UUID         NOT NULL REFERENCES posts (id),
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS follows (
    id          UUID         PRIMARY KEY,
    follower_id UUID         NOT NULL REFERENCES users (id),
    followed_id UUID         NOT NULL REFERENCES users (id),
    created_at  TIMESTAMP(6) NOT NULL,
    CONSTRAINT uk_follows_follower_followed UNIQUE (follower_id, followed_id)
);
CREATE INDEX IF NOT EXISTS idx_follows_followed_follower ON follows (followed_id, follower_id);

CREATE TABLE IF NOT EXISTS user_device (
    id           UUID         PRIMARY KEY,
    user_id      UUID         NOT NULL,
    device_id    VARCHAR(255),
    platform     VARCHAR(20)  NOT NULL,
    push_token   TEXT         NOT NULL UNIQUE,
    app_version  VARCHAR(255),
    os_version   VARCHAR(255),
    device_model VARCHAR(255),
    locale       VARCHAR(255),
    timezone     VARCHAR(255),
    is_active    BOOLEAN      NOT NULL,
    last_seen_at TIMESTAMP(6),
    created_at   TIMESTAMP(6),
    update_at    TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS user_notification (
    id         UUID         PRIMARY KEY,
    user_id    UUID         NOT NULL REFERENCES users (id),
    title      VARCHAR(255),
    body       VARCHAR(255),
    is_read    BOOLEAN      NOT NULL,
    created_at TIMESTAMP(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS fcm_broadcast_message (
    id           UUID PRIMARY KEY,
    message_name VARCHAR(255),
    title        VARCHAR(255),
    body         VARCHAR(255),
    topic        VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS job_execution_log (
    job_name         VARCHAR(255) PRIMARY KEY,
    last_executed_at TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS app_parameters (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    param_key   VARCHAR(255) NOT NULL UNIQUE,
    param_value VARCHAR(255) NOT NULL UNIQUE,
    description VARCHAR(255) NOT NULL,
    created_at  TIMESTAMP(6),
    updated_at  TIMESTAMP(6)
);

CREATE TABLE IF NOT EXISTS notification_template (
    id         UUID                     PRIMARY KEY,
    code       VARCHAR(255)             NOT NULL UNIQUE,
    title      VARCHAR(255),
    body       VARCHAR(255)             NOT NULL,
    mode       VARCHAR(255)             NOT NULL,
    category   VARCHAR(255)             NOT NULL,
    topic      VARCHAR(255),
    is_active  BOOLEAN                  NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS otp_code (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email           VARCHAR(255),
    otp             VARCHAR(255),
    expiration_time TIMESTAMP(6)
);
